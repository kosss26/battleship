export function translate(lang, key, vars) {
  let s = dict[lang]?.[key] ?? dict.ru[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v)
  return s
}

export function useLang() {
  return useStore((s) => s.profile?.language || s.lang || 'ru')
}

export function useT() {
  const lang = useLang()
  return (key, vars) => translate(lang, key, vars)
}

/** Picks the right language from a { ru, en } object */
export function useL() {
  const lang = useLang()
  return (obj) => (obj ? obj[lang] ?? obj.ru : '')
}

export const tr = (key, vars) => translate(useStore.getState().profile?.language || useStore.getState().lang || 'ru', key, vars)

export function errorText(code) {
  const k = `err_${code}`
  const s = tr(k)
  if (s !== k) return s
  const plain = tr(code)
  return plain !== code ? plain : tr('error_generic')
}

export function formatLeft(iso, t) {
  const ms = Math.max(0, new Date(iso) - Date.now())
  const d = Math.floor(ms / 86400000)
  const h = Math.floor((ms % 86400000) / 3600000)
  const m = Math.floor((ms % 3600000) / 60000)
  if (d) return `${d}${t('days')} ${h}${t('hours')}`
  if (h) return `${h}${t('hours')} ${m}${t('minutes')}`
  return `${m}${t('minutes')}`
}
