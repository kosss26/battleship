import {test,expect,uid,sql,userId,resign,expectNoPageErrors} from './helpers.js'

test('released Regent buys missing items, equips the set and plays a normal rewarded battle',async({newPlayer})=>{
  const name=`Коллекционер ${uid()}`,page=await newPlayer(name),id=await userId(name)
  await sql('UPDATE users SET gems=2000 WHERE id=$1',[id])
  await page.reload()
  await page.goto('/shop?tab=collection')
  await page.getByRole('button',{name:'Корабли',exact:true}).click()
  const ship=page.locator('.glass').filter({has:page.getByText('Регент',{exact:true})})
  await ship.getByRole('button').last().click()
  await page.getByRole('button',{name:'OK',exact:true}).click()
  await expect(ship.getByRole('button',{name:'Надеть',exact:true})).toBeVisible()
  await page.locator('[data-regent-showroom]').click()
  const buy=page.getByRole('button',{name:/Купить комплект/})
  await expect(buy).toContainText('880')
  await buy.click()
  await expect(page.getByRole('button',{name:'Надеть комплект',exact:true})).toBeVisible()
  await expect(page.locator('[data-regent-item] .regent-part-owned')).toHaveCount(4)
  const [bought]=await sql('SELECT gems,data FROM users WHERE id=$1',[id])
  expect(bought.gems).toBe(520)
  expect(bought.data.equipped.ship).toBe('ship_steel')
  await page.getByRole('button',{name:'Надеть комплект',exact:true}).click()
  await expect(page.getByRole('button',{name:'Комплект надет',exact:true})).toBeDisabled()
  await page.goto('/')
  await page.getByText('Против ИИ',{exact:true}).click()
  await page.getByText('Новичок',{exact:true}).click()
  await expect(page.getByText('Расстановка флота')).toBeVisible()
  await expect(page.locator('[data-board-theme="theme_regent"]')).toBeVisible()
  await page.getByRole('button',{name:'Готов к бою'}).click()
  await expect(page.getByText('Ваш ход')).toBeVisible()
  // Standard AI has its own ordinary waters; only our mini-board wears Regent.
  await expect(page.locator('.water').first()).toHaveAttribute('data-board-theme','theme_ocean')
  await expect(page.locator('.water').last()).toHaveAttribute('data-board-theme','theme_regent')
  await page.getByRole('button',{name:'Моё',exact:true}).click()
  await expect(page.locator('.water').first()).toHaveAttribute('data-board-theme','theme_regent')
  await resign(page)
  await expect(page.getByRole('heading',{name:'Поражение'})).toBeVisible()
  await expect(page.getByText('Пробный бой · без наград и записи в статистику')).toHaveCount(0)
  await expect(page.locator('[data-battle-report] [data-avatar-frame="frame_regent"]')).toHaveCount(1)
  const [after]=await sql('SELECT gems,data FROM users WHERE id=$1',[id])
  expect(after.gems).toBe(520)
  expect(after.data.stats.games).toBe(bought.data.stats.games+1)
  expectNoPageErrors(page)
})
